export function getLangFromUrl(url) {
  const [, lang] = url.pathname.split('/');
  if (locales.includes(lang)) return lang;
  return defaultLocale;
}

export function langPath(lang, path = '/') {
  if (lang === 'en') return `/en${path === '/' ? '/' : path}`;
  return path;
}
